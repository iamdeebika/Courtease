import hashlib
import re
from typing import List

from fastapi import Depends, HTTPException
from fastapi.responses import Response
from pydantic import BaseModel
from sqlalchemy import select
from sqlalchemy.orm import Session

from database import get_db
from models import AuditLog, Case, Order, User
from report import Report, fonts_ready


class OrderItem(BaseModel):
    id: int
    kind: str
    title: str
    date: str
    judge: str


class PapersOut(BaseModel):
    notice_available: bool
    notice_note: str
    orders: List[OrderItem]


def order_code(o) -> str:
    raw = "|".join([
        str(o.id), str(o.case_id), str(o.judge_id), o.kind, o.title, o.body, o.created_at.isoformat(),
    ])
    h = hashlib.sha256(raw.encode("utf-8")).hexdigest().upper()
    return "-".join(h[i:i + 4] for i in range(0, 16, 4))


def safe_name(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9_-]+", "_", text)


def build_notice(c, label, judge, claimant, respondent, issued, show_code, unicode_ok) -> bytes:
    pdf = Report(unicode_ok, "System-generated by CourtEase. Not a court seal.")
    pdf.add_page()
    pdf.h1("Notice to the respondent")
    pdf.body(label + " · " + c.title, 12, style="B")
    pdf.small("Produced by the CourtEase system from the court record. Prototype workflow.")

    pdf.h2("Case")
    pdf.kv("Case", label)
    pdf.kv("Title", c.title)
    pdf.kv("Type", c.case_type.split("· ", 1)[-1])
    pdf.kv("Court", c.court + ((", " + c.courtroom) if c.courtroom else ""))
    if judge:
        pdf.kv("Before", judge)
    pdf.kv("Claimant", c.claimant + (("  (advocate " + claimant + ")") if claimant else ""))
    pdf.kv("Respondent", c.respondent + (("  (advocate " + respondent + ")") if respondent else ""))
    if issued:
        pdf.kv("Notice issued", issued)
    if c.response_due:
        pdf.kv("Response due", c.response_due.strftime("%d %b %Y"))

    pdf.h2("To the respondent")
    pdf.body(
        "A case has been registered against the respondent named above. The respondent, or the advocate "
        "who acts for the respondent, must appear in this case on or before the response date shown. "
        "In CourtEase an advocate appears by choosing \"Join a case with code\", entering the case code "
        "below, and uploading the vakalatnama (the authority to appear)."
    )
    pdf.ln(2)
    if show_code and c.case_code:
        pdf.box("Case code: " + c.case_code)
    else:
        pdf.small(
            "The case code was issued to the claimant's advocate, who shares it with the "
            "respondent's advocate."
        )

    pdf.h2("What happens next")
    pdf.body(
        "When the respondent's advocate appears, the case moves to the pleadings stage. If no one appears "
        "by the response date, the judge is told that the response period has ended."
    )

    pdf.h2("About this paper")
    pdf.small(
        "This notice was produced automatically from the CourtEase record. It is not a court seal and "
        "is not legal advice. The dates and details above are those held in the record."
    )
    return bytes(pdf.output())


def build_order(o, c, label, judge, claimant, respondent, unicode_ok) -> bytes:
    pdf = Report(unicode_ok, "Issued through CourtEase. Orders are locked once issued.")
    pdf.add_page()
    pdf.h1(o.kind)
    pdf.body(label + " · " + c.title, 12, style="B")

    pdf.h2("Case")
    pdf.kv("Court", c.court + ((", " + c.courtroom) if c.courtroom else ""))
    pdf.kv("Before", judge or "The court")
    pdf.kv("Date of order", o.created_at.strftime("%d %b %Y"))
    pdf.kv("Claimant", c.claimant + (("  (advocate " + claimant + ")") if claimant else ""))
    pdf.kv("Respondent", c.respondent + (("  (advocate " + respondent + ")") if respondent else ""))

    pdf.h2(o.title)
    pdf.body(o.body, 11)
    pdf.ln(5)
    pdf.small("Issued electronically by " + (judge or "the court") + " on " + o.created_at.strftime("%d %b %Y") + ".")
    pdf.small(
        "Order fingerprint: " + order_code(o) + ". It is a short code computed from the order text as "
                                                "stored in CourtEase. If the stored text changes, the code changes."
    )
    return bytes(pdf.output())


def install_papers(app, m):
    """Adds the paper routes. 'm' is main.py, which owns the shared helpers."""

    def access(db: Session, user: User, c: Case):
        if user.role == "registry":
            return "registry", None
        if user.role == "judge":
            if c.judge_id == user.id and c.status in m.JUDGE_SEES:
                return "judge", None
        elif user.role == "lawyer":
            side = m.side_of(db, c.id, user.id)
            if side:
                return "lawyer", side
        raise HTTPException(status_code=404, detail="Case not found")

    def name_of(db: Session, uid) -> str:
        u = db.get(User, uid) if uid else None
        return u.full_name if u else ""

    def lead(db: Session, ids: list) -> str:
        return name_of(db, ids[0]) if ids else ""

    def pdf_response(data: bytes, filename: str) -> Response:
        return Response(
            content=data, media_type="application/pdf",
            headers={"Content-Disposition": 'attachment; filename="' + filename + '"', "Cache-Control": "no-store"},
        )

    @app.get("/cases/{cid}/papers", response_model=PapersOut)
    def papers(cid: int, user: User = Depends(m.approved_user), db: Session = Depends(get_db)):
        c = m.get_case(db, cid)
        kind, _side = access(db, user, c)
        has_notice = bool(c.case_code)
        note = (
                "Response due " + m.fmt_date(c.response_due) + ". The case code prints only for the registry and "
                                                               "the claimant's side."
        ) if has_notice else "No notice has been issued for this case yet."
        orders = []
        if kind in ("judge", "lawyer"):
            for o in db.scalars(select(Order).where(Order.case_id == c.id).order_by(Order.id)):
                orders.append(OrderItem(
                    id=o.id, kind=o.kind, title=o.title, date=o.created_at.strftime("%d %b %Y"),
                    judge=name_of(db, o.judge_id),
                ))
        return PapersOut(notice_available=has_notice, notice_note=note, orders=orders)

    @app.get("/cases/{cid}/notice.pdf")
    def notice_pdf(cid: int, user: User = Depends(m.approved_user), db: Session = Depends(get_db)):
        c = m.get_case(db, cid)
        kind, side = access(db, user, c)
        if not c.case_code:
            raise HTTPException(status_code=404, detail="No notice has been issued for this case")
        label = m.label(c)
        teams = m.teams_of(db, c.id)
        issued_at = db.scalar(
            select(AuditLog.created_at)
            .where(AuditLog.action == "Issued notice", AuditLog.detail.like(label + " ·%"))
            .order_by(AuditLog.id.desc()).limit(1)
        )
        data = build_notice(
            c, label, name_of(db, c.judge_id), lead(db, teams["claimant"]), lead(db, teams["respondent"]),
            issued_at.strftime("%d %b %Y") if issued_at else "",
            kind == "registry" or (kind == "lawyer" and side == "claimant"), fonts_ready(),
            )
        m.audit(db, user.id, "Downloaded notice", label)
        db.commit()
        return pdf_response(data, safe_name("CourtEase_Notice_" + label) + ".pdf")

    @app.get("/orders/{oid}/pdf")
    def order_pdf(oid: int, user: User = Depends(m.approved_user), db: Session = Depends(get_db)):
        o = db.get(Order, oid)
        if o is None:
            raise HTTPException(status_code=404, detail="Order not found")
        c = m.get_case(db, o.case_id)
        kind, _side = access(db, user, c)
        if kind == "registry":
            raise HTTPException(status_code=403, detail="Orders are available to the judge and the advocates on the case")
        label = m.label(c)
        teams = m.teams_of(db, c.id)
        data = build_order(
            o, c, label, name_of(db, o.judge_id), lead(db, teams["claimant"]), lead(db, teams["respondent"]),
            fonts_ready(),
        )
        m.audit(db, user.id, "Downloaded order", label)
        db.commit()
        return pdf_response(data, safe_name("CourtEase_Order_" + label + "_" + str(o.id)) + ".pdf")